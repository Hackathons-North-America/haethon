const { db } = await import("@/lib/db");
const { hackathons, users } = await import("@/lib/db/schema");
const { importAdminHackathons } = await import("@/lib/hackathons/review-service");
const { deleteHackathon, updatePublishedHackathon } = await import("@/lib/hackathons/admin-service");
const { generateCoverThumbnails } = await import("@/lib/hackathons/cover-thumbnails");
const { backfillCoverThumbnails } = await import("@/lib/hackathons/cover-thumbnails-backfill");
const { getPublicHackathonCatalog } = await import("@/lib/hackathons/catalog");
const { adminHackathonImportSchema, adminHackathonUpdateSchema } = await import("@/lib/validations/hackathon");

const COVER_A = "https://images.example.com/a.png";
const COVER_B = "https://images.example.com/b.png";

async function photo() {
  return new Uint8Array(await sharp(randomBytes(1600 * 800 * 3), { raw: { width: 1600, height: 800, channels: 3 } }).png().toBuffer());
}

function isoDay(daysFromNow: number) {
  return new Date(Date.now() + daysFromNow * 86_400_000).toISOString().slice(0, 10);
}

const EVENT = {
  name: "Thumbnail Test Hackathon",
  websiteUrl: "https://thumbs.example.com",
  sourceUrl: "https://thumbs.example.com",
  country: "Canada",
  city: "Toronto",
  startDate: isoDay(30),
  endDate: isoDay(31),
  format: "in_person",
};

let reviewerUserId: string;

async function thumbs(hackathonId: string) {
  const [row] = await db
    .select({
      imageUrl: hackathons.imageUrl,
      small: hackathons.imageThumbSmallUrl,
      large: hackathons.imageThumbLargeUrl,
    })
    .from(hackathons)
    .where(eq(hackathons.id, hackathonId));

  return row;
}

async function importEvent(imageUrl: string | null, overrides: Partial<typeof EVENT> = {}) {
  const parsed = adminHackathonImportSchema.parse({
    hackathons: [{ ...EVENT, ...overrides, ...(imageUrl ? { imageUrl } : {}) }],
  });
  const result = await importAdminHackathons({ payloads: parsed.hackathons, reviewerUserId });

  return result.results[0].hackathonId!;
}

function editPayload(imageUrl: string | null) {
  return adminHackathonUpdateSchema.parse({ ...EVENT, ...(imageUrl ? { imageUrl } : {}) });
}

beforeEach(async () => {
  await db.execute(sql`TRUNCATE hackathon_submissions, hackathons, hackathon_series, organizations, users CASCADE`);
  const [user] = await db
    .insert(users)
    .values({ clerkUserId: "user_admin", email: "admin@example.test", username: "admin", role: "admin" })
    .returning({ id: users.id });
  reviewerUserId = user.id;
  store.images = new Map([
    [COVER_A, await photo()],
    [COVER_B, await photo()],
  ]);
  store.uploads = 0;
  store.deleted = [];
});

describe("cover thumbnails", () => {
  it("are made for an imported cover and reach the catalog cards", async () => {
    const hackathonId = await importEvent(COVER_A);
    const row = await thumbs(hackathonId);

    expect(row.imageUrl).toBe(COVER_A);
    expect(row.small).toMatch(/^https:\/\/testapp\.ufs\.sh\/f\/\d+-cover-.+-640x320\.webp$/);
    expect(row.large).toMatch(/-1280x640\.webp$/);

    const { cards } = await getPublicHackathonCatalog({ limit: 10, sort: "soonest" });
    expect(cards.find((card) => card.id === hackathonId)).toMatchObject({
      image: COVER_A,
      imageThumbSmall: row.small,
      imageThumbLarge: row.large,
    });
  });

  it("leave a dead imported cover to be cleared, as before", async () => {
    const hackathonId = await importEvent("https://images.example.com/dead.png");

    expect(await thumbs(hackathonId)).toEqual({ imageUrl: null, small: null, large: null });
  });

  it("are replaced, and the old ones deleted, when an edit changes the image", async () => {
    const hackathonId = await importEvent(COVER_A);
    const before = await thumbs(hackathonId);

    await updatePublishedHackathon(hackathonId, editPayload(COVER_B));
    const after = await thumbs(hackathonId);

    expect(after.imageUrl).toBe(COVER_B);
    expect(after.small).toBeTruthy();
    expect(after.small).not.toBe(before.small);
    expect(store.deleted.sort()).toEqual([before.small, before.large].sort());
  });

  it("are kept when an edit leaves the image alone", async () => {
    const hackathonId = await importEvent(COVER_A);
    const before = await thumbs(hackathonId);

    await updatePublishedHackathon(hackathonId, editPayload(COVER_A));

    expect(await thumbs(hackathonId)).toEqual(before);
    expect(store.deleted).toEqual([]);
  });

  it("are cleared and deleted when an edit removes the image", async () => {
    const hackathonId = await importEvent(COVER_A);
    const before = await thumbs(hackathonId);

    await updatePublishedHackathon(hackathonId, editPayload(null));

    expect(await thumbs(hackathonId)).toEqual({ imageUrl: null, small: null, large: null });
    expect(store.deleted.sort()).toEqual([before.small, before.large].sort());
  });

  it("are deleted with the hackathon", async () => {
    const hackathonId = await importEvent(COVER_A);
    const before = await thumbs(hackathonId);

    await deleteHackathon(hackathonId);

    expect(store.deleted.sort()).toEqual([before.small, before.large].sort());
  });

  it("from a run that lost a race are thrown away, not attached to the newer image", async () => {
    const hackathonId = await importEvent(null);
    await db.update(hackathons).set({ imageUrl: COVER_B }).where(eq(hackathons.id, hackathonId));

    const result = await generateCoverThumbnails({ hackathonId, sourceUrl: COVER_A });

    expect(result).toEqual({ status: "stale" });
    expect(await thumbs(hackathonId)).toEqual({ imageUrl: COVER_B, small: null, large: null });
    expect(store.deleted).toHaveLength(2);
  });
});

describe("backfillCoverThumbnails", () => {
  async function legacyRows() {
    // Rows as they exist before the migration: an image, no thumbnails.
    const ids: string[] = [];

    for (const [index, name] of ["Alpha Builds", "Quartz Jam", "Zephyr Code Night"].entries()) {
      const site = `https://legacy-${index}.example.com`;
      ids.push(await importEvent(null, { name, websiteUrl: site, sourceUrl: site, startDate: isoDay(40 + index * 20), endDate: isoDay(41 + index * 20) }));
    }

    const images = [COVER_A, COVER_B, "https://images.example.com/broken.ico"];
    store.images.set(images[2], new Uint8Array([0, 0, 1, 0, 1, 2, 3]));

    for (const [index, id] of ids.entries()) {
      await db.update(hackathons).set({ imageUrl: images[index] }).where(eq(hackathons.id, id));
    }

    return ids;
  }

  it("--dry-run reports what is missing and writes nothing", async () => {
    const ids = await legacyRows();
    const result = await backfillCoverThumbnails({ dryRun: true });

    expect(result).toMatchObject({ pending: 3, stored: 0 });
    expect(store.uploads).toBe(0);
    for (const id of ids) {
      expect((await thumbs(id)).small).toBeNull();
    }
  });

  it("fills in what is missing, keeps going past a failure, and is idempotent", async () => {
    const ids = await legacyRows();
    const first = await backfillCoverThumbnails({ concurrency: 2 });

    expect(first).toEqual({ pending: 3, stored: 2, skipped: 0, stale: 0, failed: 1 });
    expect((await thumbs(ids[0])).small).toBeTruthy();
    expect((await thumbs(ids[1])).small).toBeTruthy();
    expect((await thumbs(ids[2])).small).toBeNull();

    const uploadsAfterFirst = store.uploads;
    const second = await backfillCoverThumbnails();

    // Only the row that failed is tried again.
    expect(second).toEqual({ pending: 1, stored: 0, skipped: 0, stale: 0, failed: 1 });
    expect(store.uploads).toBe(uploadsAfterFirst);
  });
});
